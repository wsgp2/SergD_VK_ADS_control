"""
Клиент для работы с API OpenAI (ChatGPT).
Используется для анализа данных и генерации рекомендаций.
"""
import os
import logging
from typing import List, Dict, Any, Optional
from dotenv import load_dotenv
from openai import OpenAI

# Настройка логирования
logger = logging.getLogger(__name__)

class OpenAIClient:
    """
    Клиент для работы с API OpenAI.
    Обеспечивает доступ к моделям ChatGPT для анализа данных и генерации рекомендаций.
    """
    
    DEFAULT_MODEL = "gpt-4"  # Можно изменить на более новую модель
    
    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        """
        Инициализация клиента OpenAI.
        
        Args:
            api_key: API ключ OpenAI. Если не указан, берется из переменных окружения.
            model: Модель OpenAI для использования. Если не указана, используется DEFAULT_MODEL.
        """
        load_dotenv()
        self.api_key = api_key or os.getenv('OPENAI_API_KEY')
        if not self.api_key:
            raise ValueError('Не указан API ключ OpenAI. Укажите его в .env файле или при создании клиента.')
        
        self.model = model or self.DEFAULT_MODEL
        self.client = OpenAI(api_key=self.api_key)
        
        logger.info(f"OpenAI клиент инициализирован с моделью {self.model}")
    
    def analyze_campaign_performance(self, metrics_data: Dict[str, Any]) -> str:
        """
        Анализирует эффективность рекламной кампании на основе метрик.
        
        Args:
            metrics_data: Данные метрик рекламной кампании
            
        Returns:
            Анализ эффективности в виде текста
        """
        system_prompt = """
        Ты — опытный аналитик рекламных кампаний ВКонтакте. 
        Твоя задача — проанализировать эффективность рекламной кампании на основе предоставленных метрик 
        и предложить конкретные рекомендации по улучшению показателей.
        
        Структурируй свой ответ следующим образом:
        1. Краткая сводка по ключевым метрикам
        2. Анализ эффективности (сильные и слабые стороны)
        3. 3-5 конкретных рекомендаций по улучшению
        4. Прогноз результатов после внедрения рекомендаций
        
        Используй данные для обоснования каждой рекомендации.
        """
        
        user_prompt = f"Проанализируй эффективность рекламной кампании по следующим метрикам: {metrics_data}"
        
        return self._get_completion(system_prompt, user_prompt)
    
    def evaluate_specialist(self, performance_data: Dict[str, Any]) -> str:
        """
        Оценивает работу специалиста по рекламе на основе данных о производительности кампаний.
        
        Args:
            performance_data: Данные о производительности кампаний
            
        Returns:
            Оценка работы специалиста в виде текста
        """
        system_prompt = """
        Ты — опытный руководитель отдела маркетинга.
        Твоя задача — оценить эффективность работы специалиста по рекламе ВКонтакте 
        на основе результатов рекламных кампаний.
        
        Структурируй свой ответ следующим образом:
        1. Общая оценка работы (по шкале от 1 до 10)
        2. Сильные стороны специалиста
        3. Области для улучшения
        4. Конкретные рекомендации по повышению эффективности
        
        Обрати особое внимание на:
        - Динамику ключевых показателей (CTR, CPA, ROI)
        - Соответствие результатов поставленным целям
        - Эффективность распределения бюджета
        - Качество таргетинга
        """
        
        user_prompt = f"Оцени работу специалиста по рекламе на основе следующих данных: {performance_data}"
        
        return self._get_completion(system_prompt, user_prompt)
    
    def generate_optimization_recommendations(self, campaign_data: Dict[str, Any]) -> str:
        """
        Генерирует рекомендации по оптимизации рекламной кампании.
        
        Args:
            campaign_data: Данные о рекламной кампании
            
        Returns:
            Рекомендации по оптимизации в виде текста
        """
        system_prompt = """
        Ты — эксперт по оптимизации рекламных кампаний ВКонтакте.
        Твоя задача — предложить конкретные рекомендации по оптимизации рекламной кампании
        для достижения лучших результатов.
        
        Структурируй свой ответ следующим образом:
        1. Краткий анализ текущей ситуации
        2. 5-7 конкретных рекомендаций с обоснованием:
           - Изменения в таргетинге
           - Оптимизация бюджета
           - Улучшение креативов
           - Корректировка ставок
           - Изменения в расписании показов
        3. Ожидаемый эффект от внедрения рекомендаций
        
        Рекомендации должны быть конкретными, измеримыми и реализуемыми.
        """
        
        user_prompt = f"Предложи рекомендации по оптимизации следующей рекламной кампании: {campaign_data}"
        
        return self._get_completion(system_prompt, user_prompt)
    
    def analyze_audience(self, audience_data: Dict[str, Any]) -> str:
        """
        Анализирует аудиторию рекламной кампании и предлагает улучшения таргетинга.
        
        Args:
            audience_data: Данные об аудитории
            
        Returns:
            Анализ аудитории и рекомендации по таргетингу
        """
        system_prompt = """
        Ты — эксперт по аудиториям и таргетингу в рекламе ВКонтакте.
        Твоя задача — проанализировать данные об аудитории рекламной кампании
        и предложить улучшения таргетинга для повышения эффективности.
        
        Структурируй свой ответ следующим образом:
        1. Анализ текущей аудитории (демография, интересы, поведение)
        2. Выявление наиболее конверсионных сегментов
        3. Рекомендации по корректировке таргетинга:
           - Какие сегменты усилить
           - Какие сегменты исключить
           - Новые сегменты для тестирования
        4. Стратегия для A/B тестирования разных аудиторий
        """
        
        user_prompt = f"Проанализируй аудиторию рекламной кампании на основе следующих данных: {audience_data}"
        
        return self._get_completion(system_prompt, user_prompt)
    
    def explain_performance_anomalies(self, anomaly_data: Dict[str, Any]) -> str:
        """
        Объясняет аномалии в показателях эффективности рекламной кампании.
        
        Args:
            anomaly_data: Данные об аномалиях в показателях
            
        Returns:
            Объяснение аномалий и рекомендации
        """
        system_prompt = """
        Ты — опытный аналитик рекламных кампаний.
        Твоя задача — объяснить причины аномалий в показателях эффективности рекламной кампании
        и предложить решения для исправления ситуации.
        
        Структурируй свой ответ следующим образом:
        1. Описание выявленных аномалий
        2. Возможные причины для каждой аномалии (минимум 3 гипотезы)
        3. Способы проверки каждой гипотезы
        4. Рекомендации по исправлению ситуации
        5. Превентивные меры для предотвращения подобных аномалий в будущем
        """
        
        user_prompt = f"Объясни возможные причины следующих аномалий в показателях рекламной кампании: {anomaly_data}"
        
        return self._get_completion(system_prompt, user_prompt)
    
    def _get_completion(self, system_prompt: str, user_prompt: str) -> str:
        """
        Получает ответ от модели ChatGPT.
        
        Args:
            system_prompt: Промпт для системы
            user_prompt: Промпт от пользователя
            
        Returns:
            Ответ модели
        """
        try:
            response = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                temperature=0.7,
                max_tokens=2000
            )
            
            return response.choices[0].message.content
            
        except Exception as e:
            logger.error(f"Ошибка при получении ответа от OpenAI: {e}")
            return f"Произошла ошибка при анализе данных: {e}"


# Пример использования
if __name__ == "__main__":
    # Настройка логирования
    logging.basicConfig(level=logging.INFO)
    
    try:
        # Создание клиента
        client = OpenAIClient()
        
        # Пример анализа кампании
        test_data = {
            "campaign_name": "Тестовая кампания",
            "period": "last_7_days",
            "metrics": {
                "impressions": 15000,
                "clicks": 450,
                "ctr": 3.0,
                "cpc": 12.5,
                "spend": 5625,
                "conversions": 25,
                "cpa": 225,
                "roi": 1.8
            }
        }
        
        analysis = client.analyze_campaign_performance(test_data)
        print(analysis)
        
    except Exception as e:
        print(f"Произошла ошибка: {e}")
